// Shared references are authored in plugins/<plugin>/reference.md.
import { lstatSync, mkdtempSync, readFileSync, readdirSync, readlinkSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

function stat(path) {
  try { return lstatSync(path); }
  catch (error) {
    if (error.code === "ENOENT") return null;
    throw error;
  }
}

// Plan every update before writing, so unexpected destinations abort the batch.
export function syncReferences(root, { check = false } = {}) {
  const updates = [];
  for (const plugin of readdirSync(join(root, "plugins"), { withFileTypes: true })) {
    if (!plugin.isDirectory()) continue;
    const source = join(root, "plugins", plugin.name, "reference.md");
    const sourceStat = stat(source);
    if (!sourceStat) continue; // A skill need not have a shared reference.
    if (!sourceStat.isFile()) throw new Error(`Expected a regular source file: ${source}`);
    const skills = join(dirname(source), "skills");
    if (!stat(skills)) continue;
    const content = "<!-- Generated by sync-references.mjs. Edit plugins/" + plugin.name
      + "/reference.md, then run make sync-references. Do not edit this copy. -->\n\n"
      + readFileSync(source, "utf8");
    for (const skill of readdirSync(skills, { withFileTypes: true })) {
      if (!skill.isDirectory() || !stat(join(skills, skill.name, "SKILL.md"))) continue;
      const destination = join(skills, skill.name, "reference.md");
      const current = stat(destination);
      if (current?.isSymbolicLink()) {
        if (resolve(dirname(destination), readlinkSync(destination)) !== resolve(source)) {
          throw new Error(`Refusing an unrelated symlink: ${destination}`);
        }
      } else if (current && !current.isFile()) {
        throw new Error(`Expected a regular destination file: ${destination}`);
      }
      if (!current?.isFile() || readFileSync(destination, "utf8") !== content) {
        updates.push({ destination, content });
      }
    }
  }
  if (!check) {
    for (const { destination, content } of updates) {
      const staging = mkdtempSync(`${destination}.`);
      const temporary = join(staging, "reference.md");
      try {
        writeFileSync(temporary, content, { flag: "wx" });
        renameSync(temporary, destination); // Replace legacy links without writing through them.
      } finally {
        rmSync(staging, { recursive: true, force: true });
      }
    }
  }
  return updates.map(({ destination }) => relative(root, destination));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    if (process.argv.slice(2).some((arg) => arg !== "--check")) {
      throw new Error("Usage: node sync-references.mjs [--check]");
    }
    const check = process.argv.includes("--check");
    const changed = syncReferences(dirname(fileURLToPath(import.meta.url)), { check });
    if (check && changed.length) {
      console.error(`Shared references are out of sync. Run make sync-references:\n${changed.join("\n")}`);
      process.exitCode = 1;
    } else {
      console.log(check ? "Shared references are in sync." : `Synced ${changed.length} shared references.`);
    }
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}

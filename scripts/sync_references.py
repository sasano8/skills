#!/usr/bin/env python3
"""Copy shared plugin references into independently distributable skills."""

import argparse
import os
from pathlib import Path
import sys
import tempfile


def sync_references(root: Path, *, check: bool = False) -> list[str]:
    """Plan the entire batch before writing; check mode never modifies files."""
    updates = []
    for plugin in sorted((root / "plugins").iterdir()):
        if not plugin.is_dir() or plugin.is_symlink():
            continue
        source = plugin / "reference.md"
        if not source.exists() and not source.is_symlink():
            continue  # Shared references are optional.
        if not source.is_file() or source.is_symlink():
            raise ValueError(f"Expected a regular source file: {source}")
        skills = plugin / "skills"
        if not skills.exists():
            continue
        header = (
            "<!-- Generated by scripts/sync_references.py. Edit plugins/"
            f"{plugin.name}/reference.md, then run make sync-references. "
            "Do not edit this copy. -->\n\n"
        )
        content = header.encode("utf-8") + source.read_bytes()
        for skill in sorted(skills.iterdir()):
            if not skill.is_dir() or skill.is_symlink() or not (skill / "SKILL.md").is_file():
                continue
            destination = skill / "reference.md"
            if destination.is_symlink():
                target = os.path.abspath(destination.parent / os.readlink(destination))
                if target != os.path.abspath(source):
                    raise ValueError(f"Refusing an unrelated symlink: {destination}")
            elif destination.exists() and not destination.is_file():
                raise ValueError(f"Expected a regular destination file: {destination}")
            if destination.is_symlink() or not destination.exists() or destination.read_bytes() != content:
                updates.append((destination, content))

    if not check:
        for destination, content in updates:
            with tempfile.TemporaryDirectory(prefix=".sync-references-", dir=destination.parent) as staging:
                temporary = Path(staging) / "reference.md"
                temporary.write_bytes(content)
                # Replace legacy links without writing through them.
                os.replace(temporary, destination)
    return [path.relative_to(root).as_posix() for path, _ in updates]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="report stale copies without writing")
    args = parser.parse_args()
    try:
        changed = sync_references(Path(__file__).resolve().parent.parent, check=args.check)
    except (OSError, ValueError) as error:
        print(error, file=sys.stderr)
        return 1
    if args.check and changed:
        print("Shared references are out of sync. Run make sync-references:", file=sys.stderr)
        print("\n".join(changed), file=sys.stderr)
        return 1
    print("Shared references are in sync." if args.check else f"Synced {len(changed)} shared references.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
